'''ORM：对象关系映射'''
"""
问题：后端请求数据库，数据库把数据传给后端，但是后端如何保存呢？
    不可能用字典，列表、元组保存起来，这么太零碎了。
    
解决方法：（面向对象的思维）
    在实际开发中，我们将数据库中的表映射为后端的类    （ “类名”和“数据表名”保持一致）
    数据库中的列，映射为后端的属性                 （“类的属性”和“表的列名”保持一致）
    数据库返回的每条数据，映射为后端的对象  
（严格对照：表名和类名对应，列名和属性名对应）          
这就是ORM的主要思想，让开发者可以用面向对象的方式操作数据库，而无需直接编写SQL语句

ORM的核心价值：
    屏蔽数据库差异：同一套代码适配多种数据库（MySQL、PostgreSQL等）
    简化开发流程：用类、对象、方法替代SQL语句，简化学习
    自动处理类型转换：无需手动转换数据库字段与Python类型
    
常见的名词解释：
    引擎Engine：Engine是与数据库的连接入口，负责管理连接池和执行SQL语句
    基类Base：所有ORM模型的父类，用于统一管理数据库表结构
    会话Session：用于执行数据库操作的会话对象，负责暂存、提交、回滚数据操作
    
根据类生成数据库
根据数据库生成类
"""
"""
数据表和python代码对应起来
    表名 → 类名
    列名 → 属性名
    列的类型 → 属性的类型
    单元格的数据 → 属性值
    每一行数据 → 类对象
        第一行数据：user1 = User(1,'tom',28)
        第二行数据：user2 = User(1,'jack',31)
"""